"""Tests for histogram analysis, Shannon entropy, and comb artifacts."""

from PIL import Image
import numpy as np
import cv2
import pytest

from forensic.histogram import perform_histogram_analysis, compute_entropy, detect_comb_effect


def test_entropy_calculation():
    """Verify Shannon entropy computation."""
    # Uniform distribution across 256 states has maximum entropy log2(256) = 8.0 bits
    uniform_counts = np.ones(256)
    entropy_max = compute_entropy(uniform_counts)
    assert abs(entropy_max - 8.0) < 0.01

    # Single-state distribution has 0.0 bits
    single_state = np.zeros(256)
    single_state[100] = 500
    entropy_min = compute_entropy(single_state)
    assert entropy_min == 0.0


def test_perform_histogram_analysis_basic():
    """Verify histogram extraction and moment computation."""
    arr = np.linspace(0, 255, 10000, dtype=np.uint8).reshape(100, 100)
    img = Image.fromarray(arr).convert("RGB")
    
    stats = perform_histogram_analysis(img)
    assert len(stats["hist_gray"]) == 256
    assert len(stats["hist_r"]) == 256
    assert "gray_mean" in stats
    assert "gray_entropy" in stats
    assert stats["gray_entropy"] > 6.0


def test_detect_comb_effect():
    """Verify detection of comb-like spacing generated by histogram stretching."""
    # Create histogram with deliberate empty bins (comb effect)
    comb_hist = np.zeros(256)
    for i in range(20, 220, 4):  # Only every 4th bin has values
        comb_hist[i] = 100

    is_comb, zero_gaps, ratio = detect_comb_effect(comb_hist)
    assert is_comb is True
    assert zero_gaps > 30
    assert ratio > 0.15
